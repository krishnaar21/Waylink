"""Converts the web app's Hugeicons set (web-v0/js/icons-huge.js) into Android vector drawables.

Needs Node 18+. Run from the repo root:  python3 android/tools/icons_to_vectors.py
Writes android/app/src/main/res/drawable/ic_<name>.xml. Colours are black; Compose tints them.
"""
import json, os, re, sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'web-v0', 'js', 'icons-huge.js')
OUT = os.path.join(ROOT, 'android', 'app', 'src', 'main', 'res', 'drawable')
KT = os.path.join(ROOT, 'android', 'app', 'src', 'main', 'java', 'app', 'waylink', 'ui', 'components', 'IconMap.kt')

def snake(n):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', n).lower().replace('-', '_')

def circle_path(cx, cy, r):
    return f'M{cx - r},{cy}a{r},{r} 0 1,0 {2 * r},0a{r},{r} 0 1,0 {-2 * r},0'

def rect_path(x, y, w, h, rx):
    if not rx:
        return f'M{x},{y}h{w}v{h}h{-w}z'
    return (f'M{x + rx},{y}h{w - 2 * rx}a{rx},{rx} 0 0 1 {rx},{rx}v{h - 2 * rx}a{rx},{rx} 0 0 1 {-rx},{rx}'
            f'h{-(w - 2 * rx)}a{rx},{rx} 0 0 1 {-rx},{-rx}v{-(h - 2 * rx)}a{rx},{rx} 0 0 1 {rx},{-rx}z')

INHERIT = ('fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin', 'opacity', 'fill-rule')

def walk(el, ctx, out):
    ctx = dict(ctx)
    for k in INHERIT:
        if k in el.attrib:
            ctx[k] = el.attrib[k] if k != 'opacity' else float(ctx.get('opacity', 1)) * float(el.attrib[k])
    tag = el.tag.split('}')[-1]
    d = None
    f = lambda k, dflt=0: float(el.attrib.get(k, dflt))
    if tag == 'path': d = el.attrib['d']
    elif tag == 'circle': d = circle_path(f('cx'), f('cy'), f('r'))
    elif tag == 'ellipse':
        cx, cy, rx, ry = f('cx'), f('cy'), f('rx'), f('ry')
        d = f'M{cx - rx},{cy}a{rx},{ry} 0 1,0 {2 * rx},0a{rx},{ry} 0 1,0 {-2 * rx},0'
    elif tag == 'rect': d = rect_path(f('x'), f('y'), f('width'), f('height'), f('rx', el.attrib.get('ry', 0)))
    elif tag == 'line': d = f"M{f('x1')},{f('y1')}L{f('x2')},{f('y2')}"
    elif tag in ('polyline', 'polygon'):
        pts = el.attrib['points'].replace(',', ' ').split()
        d = 'M' + ' '.join(pts) + ('z' if tag == 'polygon' else '')
    if d:
        out.append((d, ctx))
    for c in el:
        walk(c, ctx, out)

def to_vector(svg_inner):
    root = ET.fromstring(f'<svg xmlns="http://www.w3.org/2000/svg">{svg_inner}</svg>')
    paths = []
    walk(root, {'fill': 'none', 'opacity': 1.0}, paths)
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- Generated by android/tools/icons_to_vectors.py from Hugeicons (MIT). Do not edit. -->',
             '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
             '    android:width="24dp" android:height="24dp"',
             '    android:viewportWidth="26" android:viewportHeight="26">',
             '  <group android:translateX="1" android:translateY="1">']
    for d, c in paths:
        a = [f'android:pathData="{d}"']
        op = float(c.get('opacity', 1))
        fill = c.get('fill', 'none')
        if fill != 'none':
            a.append('android:fillColor="#FF000000"')
            if op < 1: a.append(f'android:fillAlpha="{op:g}"')
            if c.get('fill-rule') == 'evenodd': a.append('android:fillType="evenOdd"')
        stroke = c.get('stroke')
        if stroke and stroke != 'none':
            a.append('android:strokeColor="#FF000000"')
            a.append(f'android:strokeWidth="{c.get("stroke-width", "1")}"')
            if op < 1: a.append(f'android:strokeAlpha="{op:g}"')
            cap = c.get('stroke-linecap'); join = c.get('stroke-linejoin')
            if cap in ('round', 'square'): a.append(f'android:strokeLineCap="{cap}"')
            if join in ('round', 'bevel'): a.append(f'android:strokeLineJoin="{join}"')
        lines.append('    <path ' + '\n        '.join(a) + '/>')
    lines += ['  </group>', '</vector>', '']
    return '\n'.join(lines)

def main():
    # Node reads the ES module as-is, so the web file stays the single source of truth.
    import subprocess
    out = subprocess.run(['node', '--input-type=module', '-e',
                          f"import {{ ICONS }} from {json.dumps('file://' + SRC)}; process.stdout.write(JSON.stringify(ICONS))"],
                         check=True, capture_output=True, text=True).stdout
    icons = json.loads(out)
    os.makedirs(OUT, exist_ok=True)
    names = []
    for name, svg in icons.items():
        try:
            xml = to_vector(svg)
        except Exception as e:  # keep going; report at the end
            print('skip', name, e, file=sys.stderr); continue
        n = 'ic_' + snake(name)
        open(os.path.join(OUT, n + '.xml'), 'w', encoding='utf-8').write(xml)
        names.append((name, n))
    # A typed map from the web app's icon names, so code can say Ic("wrench") like the web views do,
    # and resource shrinking still sees every icon in use.
    rows = ',\n'.join(f'        "{web}" to R.drawable.{n}' for web, n in names)
    open(KT, 'w', encoding='utf-8').write(f'''package app.waylink.ui.components

import app.waylink.R

// Generated by android/tools/icons_to_vectors.py. Do not edit.
internal object IconMap {{
    val byName: Map<String, Int> = mapOf(
{rows},
    )
}}
''')
    print(f'{len(names)} icons written to {OUT} and {KT}')

if __name__ == '__main__':
    main()
